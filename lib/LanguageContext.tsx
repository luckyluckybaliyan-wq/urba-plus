interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>('en');

  useEffect(() => {
    const saved = localStorage.getItem('crowdcivic_lang') as LanguageCode;
    if (saved && TRANSLATIONS[saved]) {
      setLanguageState(saved);
    }

    const handleLangSync = () => {
      const current = localStorage.getItem('crowdcivic_lang') as LanguageCode;
      if (current && TRANSLATIONS[current]) {
        setLanguageState(current);
      }
    };

    window.addEventListener('storage', handleLangSync);
    window.addEventListener('crowdcivic_lang_changed', handleLangSync);

    return () => {
      window.removeEventListener('storage', handleLangSync);
      window.removeEventListener('crowdcivic_lang_changed', handleLangSync);
    };
  }, []);

  const setLanguage = (code: LanguageCode) => {
    setLanguageState(code);
    localStorage.setItem('crowdcivic_lang', code);
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new Event('crowdcivic_lang_changed'));
    }
  };

  const t = (key: string, fallback?: string): string => {
    if (TRANSLATIONS[language] && TRANSLATIONS[language][key]) {
      return TRANSLATIONS[language][key];
    }
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}

export function LanguageSelector({
  className = '',
  compact = false,
}: {
  className?: string;
  compact?: boolean;
}) {
  const { language, setLanguage } = useLanguage();
  return (
    <div className={`relative inline-flex items-center shrink-0 ${className}`}>
      <select
        value={language}
        onChange={(e) => setLanguage(e.target.value as LanguageCode)}
        className={`bg-white hover:bg-slate-50 text-slate-800 text-xs font-semibold rounded-xl border border-slate-200 focus:outline-none focus:ring-2 focus:ring-blue-500/20 cursor-pointer transition-all shadow-2xs ${
          compact ? 'px-2.5 py-1.5 text-[11px]' : 'px-3 py-1.5'
        }`}
        aria-label="Select Language"
      >
        {LANGUAGES.map((lang) => (
          <option key={lang.code} value={lang.code} className="bg-white text-slate-800">
            {compact ? lang.nativeName : `${lang.nativeName} (${lang.name})`}
          </option>
        ))}
      </select>
    </div>
  );
}
